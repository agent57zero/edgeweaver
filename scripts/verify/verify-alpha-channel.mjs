#!/usr/bin/env node
// verify-alpha-channel.mjs - offline invariants for Alpha's channel config (birth run B6).
// No network, no secrets printed, no channel opened. Checks:
//   1. the watchdog launcher exists, is ASCII-only, targets the alpha skill + state dir,
//      and its process marker is skill-specific (so is Genesis's, the cross-match fix);
//   2. if the generated plugin state exists, access.json parses with dmPolicy allowlist,
//      six seat ids, and exactly one pinned group with requireMention false;
//   3. the session policy config (avatars/alpha/state/channel-policy.json), if present,
//      matches the multi-sender policy shape: 6 seats, quorum 3, lessonConfirmSeats 1,
//      and classifySender actually defers an unknown and ignores a bot under it;
//   4. the ops sender refuses without the armed marker (static check of the guard).
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";
import { classifySender } from "../telegram/multi-sender-policy.mjs";

const ROOT = join(import.meta.dirname, "..", "..");
const fail = (m) => { console.log(`FAIL: ${m}`); process.exit(1); };

// 1. launcher/watchdog
const wd = join(ROOT, "scripts", "ops", "alpha-channel-watchdog.ps1");
if (!existsSync(wd)) fail("alpha-channel-watchdog.ps1 missing");
const wdText = readFileSync(wd, "utf8");
if (/[^\x00-\x7F]/.test(wdText)) fail("watchdog is not ASCII-only");
for (const needle of ["wake-edgeweaver-alpha", "TELEGRAM_STATE_DIR", "telegram-alpha", "EdgeweaverAlphaTelegram"])
  if (!wdText.includes(needle)) fail(`watchdog missing '${needle}'`);
const gwd = readFileSync(join(ROOT, "scripts", "ops", "genesis-channel-watchdog.ps1"), "utf8");
if (!gwd.includes("wake-edgeweaver-genesis*--channels")) fail("genesis watchdog marker is not skill-specific (cross-match with alpha)");

// 2. plugin state (generated by alpha-channel-config.mjs; optional on a fresh clone)
const stateDir = join(homedir(), ".claude", "channels", "telegram-alpha");
let stateNote = "plugin state not generated on this machine (ok on a fresh clone)";
if (existsSync(join(stateDir, "access.json"))) {
  const a = JSON.parse(readFileSync(join(stateDir, "access.json"), "utf8"));
  if (a.dmPolicy !== "allowlist") fail(`dmPolicy is '${a.dmPolicy}', expected allowlist (fail-closed, no pairing codes)`);
  if (!Array.isArray(a.allowFrom) || a.allowFrom.length < 6) fail(`allowFrom has ${a.allowFrom?.length}, expected >= 6 seat ids`);
  const groups = Object.entries(a.groups || {});
  if (groups.length !== 1) fail(`expected exactly 1 pinned group, got ${groups.length}`);
  if (groups[0][1].requireMention !== false) fail("group requireMention should be false (dedicated group = its own room)");
  if (!existsSync(join(stateDir, ".env"))) fail("plugin .env missing beside access.json");
  stateNote = `plugin state ok (${a.allowFrom.length} DM ids, group pinned)`;
}

// 3. session policy config
const polPath = join(ROOT, "avatars", "alpha", "state", "channel-policy.json");
let polNote = "policy config not generated on this machine (ok on a fresh clone)";
if (existsSync(polPath)) {
  const p = JSON.parse(readFileSync(polPath, "utf8"));
  if (Object.keys(p.seats || {}).length !== 6) fail("policy config: expected 6 seats");
  if (p.quorum !== 3) fail(`policy config: quorum ${p.quorum}, expected 3 (G19)`);
  if (p.lessonConfirmSeats !== 1) fail("policy config: lessonConfirmSeats should be 1");
  const unknown = classifySender("999999999", p);
  if (unknown.action !== "defer" || unknown.untrusted !== true) fail("unknown sender not deferred untrusted under the config");
  const bot = classifySender({ id: Object.keys(p.seats)[0], is_bot: true }, p);
  if (bot.action !== "ignore") fail("bot sender not ignored under the config");
  const seat = classifySender(Object.keys(p.seats)[0], p);
  if (!seat.is_seat || seat.action !== "reply") fail("seat id not classified as seat");
  polNote = "policy config ok (6 seats, quorum 3, defer/ignore/reply verified)";
}

// 4. ops sender guard
const sender = readFileSync(join(ROOT, "scripts", "ops", "send-telegram-alpha.mjs"), "utf8");
if (!sender.includes("alpha-channel-armed")) fail("send-telegram-alpha.mjs lacks the pre-birth armed-marker guard");

console.log(`PASS: alpha channel dark config - watchdog ok; ${stateNote}; ${polNote}; sender guard present`);
