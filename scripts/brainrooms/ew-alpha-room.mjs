// ew-alpha-room.mjs - Alpha's brain room (FAMILY §4, plan M2), built DARK ahead of arming.
// Generates and rehearses the ew_alpha schema + dedicated runtime role + curated corpus view.
//
//   node scripts/brainrooms/ew-alpha-room.mjs --emit-sql          print the SQL, no connection
//   node scripts/brainrooms/ew-alpha-room.mjs --target lab        full rehearsal on the lab brain
//                                                                 (build, wall-test, retire; 0 residue)
//   node scripts/brainrooms/ew-alpha-room.mjs --target lab --clean  drop rehearsal residue only
//   node scripts/brainrooms/ew-alpha-room.mjs --target live ...   REFUSES unless the A2 gate is
//                                                                 cleared in decisions.md and its row
//                                                                 id is passed via EW_A2_GATE_REF plus
//                                                                 an explicit --confirm-live flag.
//
// Design (D18/FAMILY §4): the role is Alpha's ONLY runtime credential - full rights inside
// ew_alpha, SELECT on the corpus view, nothing else. The view is the wall's one window: it
// exposes library-class rows only (allowlist source_type IN pm_teaching, coherence_teaching;
// conventions/memory-conventions.md), reads its source with the OWNER's rights (default
// Postgres view semantics), and the role gets SELECT only, so the auto-updatable-view write
// path is closed by grants. Room v1 contains the thoughts mirror; the full organ set lands
// at the A2 arming pass through the same OB1 recipes Genesis used.
//
// Rehearsal honesty: on the lab, the protected source is a stand-in table in a rehearsal
// schema (the lab has no real public.thoughts); the mechanism is what is proven. The live
// apply re-runs the same wall test against the real public.thoughts at arming.
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { runSqlText, query } from "../brains/db.mjs";

const ROOT = join(import.meta.dirname, "..", "..");
const ROLE = "ew_alpha_runtime";
const LIBRARY_TYPES = ["pm_teaching", "coherence_teaching"]; // allowlist, never a blocklist
const VIEW_COLUMNS = [
  "id", "content", "embedding", "metadata", "created_at", "updated_at",
  "source_type", "type", "importance", "quality_score",
];

function loadEnv(file) {
  try {
    return Object.fromEntries(
      readFileSync(file, "utf8").split(/\r?\n/)
        .map((l) => l.match(/^([A-Za-z0-9_]+)=(.*)$/)).filter(Boolean).map((m) => [m[1], m[2]])
    );
  } catch { return {}; }
}

// The room's own memory table (thoughts mirror, shape from brains/schema/ddl-v1.sql).
function thoughtsDdl(schema) {
  return `CREATE TABLE ${schema}.thoughts (
    id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    content text NOT NULL,
    embedding public.vector(1536),
    metadata jsonb DEFAULT '{}'::jsonb,
    created_at timestamp with time zone DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    content_fingerprint text,
    type text,
    sensitivity_tier text DEFAULT 'standard'::text,
    importance smallint DEFAULT 3,
    quality_score numeric(5,2) DEFAULT 50,
    source_type text,
    enriched boolean DEFAULT false,
    status text,
    status_updated_at timestamp with time zone DEFAULT now()
);`;
}

// The full room build. sourceTable = the protected library source (live: public.thoughts).
export function roomSql({ sourceTable, password }) {
  const filter = LIBRARY_TYPES.map((t) => `'${t}'`).join(", ");
  return `-- ew_alpha room v1 (generated by scripts/brainrooms/ew-alpha-room.mjs; do not hand-edit)
CREATE SCHEMA ew_alpha;
${thoughtsDdl("ew_alpha")}

-- Alpha's ONLY runtime credential (FAMILY §4). No superuser, no create, no replication.
CREATE ROLE ${ROLE} LOGIN PASSWORD '${password}'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
-- Supabase's admin (postgres) is NOT a superuser: without membership it cannot administer
-- or drop this role's objects (found by the lab rehearsal). Membership grants the ADMIN
-- power over the role, never the reverse; the role's own reach is unchanged.
-- Dynamic form on purpose: the literal "GRANT ... TO CURRENT_USER" keyword form crashed the
-- Supabase backend outright (lab rehearsal, 2026-07-16, deterministic at this statement);
-- resolving the name first is the same grant and survives.
DO $$ BEGIN EXECUTE 'GRANT ${ROLE} TO ' || quote_ident(current_user); END $$;

-- Own room: full rights inside ew_alpha and nothing else.
GRANT USAGE ON SCHEMA ew_alpha TO ${ROLE};
GRANT ALL ON ALL TABLES IN SCHEMA ew_alpha TO ${ROLE};
ALTER DEFAULT PRIVILEGES IN SCHEMA ew_alpha GRANT ALL ON TABLES TO ${ROLE};

-- The one window: a curated corpus view, library-class allowlist only, owner-rights read.
-- Explicit column list (frozen surface; drift is a deliberate re-create, never silent).
CREATE VIEW ew_alpha.pm_corpus AS
  SELECT ${VIEW_COLUMNS.join(", ")}
  FROM ${sourceTable}
  WHERE source_type IN (${filter});
-- The default-privileges rule above covers VIEWS too (they are relations), so the view was
-- just auto-granted ALL - a real breach the lab rehearsal caught (2026-07-16): the role
-- could write the protected source through the auto-updatable view. Revoke, then narrow:
REVOKE ALL ON ew_alpha.pm_corpus FROM ${ROLE};
GRANT SELECT ON ew_alpha.pm_corpus TO ${ROLE};
-- SELECT only: simple views are auto-updatable in Postgres, so the write path through the
-- view is closed by withholding INSERT/UPDATE/DELETE grants, tested below.

-- Belt and braces: the role never creates outside its room.
REVOKE CREATE ON SCHEMA public FROM ${ROLE};
`;
}

// Rehearsal-only fixtures: a protected stand-in source with one library canary and one
// private canary, in its own schema the role is never granted.
function rehearsalFixturesSql() {
  return `CREATE SCHEMA ew_rehearsal_private;
${thoughtsDdl("ew_rehearsal_private")}
INSERT INTO ew_rehearsal_private.thoughts (content, source_type, metadata)
VALUES ('REHEARSAL library canary', 'pm_teaching',
        '{"rehearsal": true, "license": "CC-BY-SA-4.0", "attribution": "Clinton Callahan / Possibility Management"}'::jsonb),
       ('REHEARSAL private canary - must never be visible to the role', 'edgeweaver_episode',
        '{"rehearsal": true}'::jsonb);
`;
}

// Robust against partial builds and the non-superuser admin: terminate any lingering
// backends for the role (a pooled session can outlive DROP ROLE and resurface under the
// old role OID, where new grants never apply - seen on the lab pooler), (re)grant
// membership before DROP OWNED, and skip role teardown when the role never got created.
const retireSql = `DO $$ BEGIN
  IF EXISTS (SELECT FROM pg_roles WHERE rolname = '${ROLE}') THEN
    PERFORM pg_terminate_backend(pid) FROM pg_stat_activity WHERE usename = '${ROLE}';
    EXECUTE 'GRANT ${ROLE} TO ' || quote_ident(current_user);
    EXECUTE 'DROP OWNED BY ${ROLE}';
    EXECUTE 'DROP ROLE ${ROLE}';
  END IF;
END $$;
DROP SCHEMA IF EXISTS ew_alpha CASCADE;
DROP SCHEMA IF EXISTS ew_rehearsal_private CASCADE;`;

// Build the role's own connection URL from the admin URL (Supabase pooler usernames are
// user.projectref; keep the ref when present).
export function roleUrl(adminUrl, password) {
  const m = adminUrl.match(/^(postgres(?:ql)?:\/\/)([^:]+):([^@]+)@(.*)$/);
  if (!m) throw new Error("cannot parse the admin connection URL shape");
  const adminUser = decodeURIComponent(m[2]);
  const dot = adminUser.indexOf(".");
  const user = dot === -1 ? ROLE : `${ROLE}.${adminUser.slice(dot + 1)}`;
  return `${m[1]}${encodeURIComponent(user)}:${encodeURIComponent(password)}@${m[4]}`;
}

function expectDenied(fn, label, results) {
  try { fn(); results.push(`FAIL ${label}: was ALLOWED (wall breach)`); return false; }
  catch (e) {
    if (/permission denied/i.test(e.message)) { results.push(`PASS ${label}: permission denied`); return true; }
    results.push(`FAIL ${label}: unexpected error class: ${e.message.split("\n")[0]}`);
    return false;
  }
}

function rehearse(labUrl) {
  const password = randomBytes(24).toString("base64url");
  const results = [];
  let ok = true;
  try {
    runSqlText(labUrl, rehearsalFixturesSql(), "ew-alpha-fixtures");
    runSqlText(labUrl, roomSql({ sourceTable: "ew_rehearsal_private.thoughts", password }), "ew-alpha-room");
    // Belt and braces against pooled sessions from an aborted earlier run (see retireSql).
    query(labUrl, `SELECT count(pg_terminate_backend(pid)) FROM pg_stat_activity WHERE usename = '${ROLE}'`);
    const asRole = roleUrl(labUrl, password);

    query(asRole, "INSERT INTO ew_alpha.thoughts (content, source_type) VALUES ('room write test', 'edgeweaver_episode')");
    const own = query(asRole, "SELECT count(*) FROM ew_alpha.thoughts");
    results.push(own[0][0] === "1" ? "PASS own room: write + read" : `FAIL own room: expected 1 row, got ${own[0][0]}`);

    ok = expectDenied(() => query(asRole, "SELECT count(*) FROM ew_rehearsal_private.thoughts"), "protected source direct read", results) && ok;
    const corpus = query(asRole, "SELECT content, source_type FROM ew_alpha.pm_corpus");
    const corpusOk = corpus.length === 1 && corpus[0][1] === "pm_teaching";
    results.push(corpusOk ? "PASS corpus view: exactly the library canary, private canary invisible"
                          : `FAIL corpus view: got ${corpus.length} row(s): ${JSON.stringify(corpus)}`);
    ok = corpusOk && ok;
    ok = expectDenied(() => query(asRole, "UPDATE ew_alpha.pm_corpus SET content = 'defaced'"), "write through the view", results) && ok;
    ok = expectDenied(() => query(asRole, "CREATE TABLE ew_rehearsal_private.intruder (id int)"), "create outside the room", results) && ok;
    ok = results.every((r) => r.startsWith("PASS")) && ok;
  } finally {
    runSqlText(labUrl, retireSql, "ew-alpha-retire");
    const residue = query(labUrl,
      `SELECT count(*) FROM pg_namespace WHERE nspname IN ('ew_alpha','ew_rehearsal_private')`)[0][0];
    const roleLeft = query(labUrl, `SELECT count(*) FROM pg_roles WHERE rolname = '${ROLE}'`)[0][0];
    results.push(residue === "0" && roleLeft === "0" ? "PASS retire: zero residue (schemas + role gone)"
                                                     : `FAIL retire: residue schemas=${residue} role=${roleLeft}`);
    ok = ok && residue === "0" && roleLeft === "0";
  }
  return { ok, results };
}

