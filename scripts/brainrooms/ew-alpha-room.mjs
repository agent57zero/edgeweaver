function main() {
const args = process.argv.slice(2);
const has = (f) => args.includes(f);
const target = args[args.indexOf("--target") + 1];

if (has("--emit-sql")) {
  console.log(roomSql({ sourceTable: "public.thoughts", password: "<generated-at-apply>" }));
  process.exit(0);
}

if (target === "live") {
  const gateRef = process.env.EW_A2_GATE_REF || "";
  if (!gateRef || !has("--confirm-live")) {
    console.log("REFUSED: the live apply is Alpha's A2 arming and sits behind the G19 gate " +
      "(decisions.md; FAMILY §7). When the ledger carries the gate decision, set " +
      "EW_A2_GATE_REF=<decision row id> and pass --confirm-live. Nothing was touched.");
    process.exit(1);
  }
  const env = loadEnv(join(ROOT, ".env.local"));
  if (!env.SUPABASE_DB_URL) { console.log("FAIL: SUPABASE_DB_URL missing from .env.local"); process.exit(1); }
  const password = randomBytes(24).toString("base64url");
  runSqlText(env.SUPABASE_DB_URL, roomSql({ sourceTable: "public.thoughts", password }), "ew-alpha-room-live");
  const alphaEnvPath = join(ROOT, "avatars", "alpha", ".env.local");
  const url = roleUrl(env.SUPABASE_DB_URL, password);
  const prev = existsSync(alphaEnvPath) ? readFileSync(alphaEnvPath, "utf8") : "";
  writeFileSync(alphaEnvPath, prev.replace(/\n?$/, "\n") +
    `# ew_alpha runtime credential (created at A2 apply, gate ref ${gateRef}); Alpha's ONLY runtime credential:\nEW_ALPHA_DB_URL=${url}\n`, "utf8");
  console.log(`LIVE APPLY DONE under gate ref ${gateRef}: ew_alpha room created; role credential written to avatars/alpha/.env.local (EW_ALPHA_DB_URL). Run the arming wall test next (checklist A2).`);
  process.exit(0);
}

// default: lab rehearsal
const env = loadEnv(join(ROOT, ".env.local"));
if (!env.LAB_DB_URL) { console.log("FAIL: LAB_DB_URL missing from .env.local (brain lab, D15)"); process.exit(1); }
if (has("--clean")) {
  runSqlText(env.LAB_DB_URL, retireSql, "ew-alpha-clean");
  console.log("cleaned: rehearsal schemas + role dropped if present");
  process.exit(0);
}
const { ok, results } = rehearse(env.LAB_DB_URL);
console.log((ok ? "PASS" : "FAIL") + ": ew_alpha room rehearsal on the lab brain\n - " + results.join("\n - "));
process.exit(ok ? 0 : 1);
}
